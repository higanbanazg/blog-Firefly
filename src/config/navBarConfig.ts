// ============================================================================
// 导航栏配置 - 根据顺序动态生成导航栏链接
// NavBar Configuration - Dynamically generate navigation bar links based on order
// ============================================================================
const getDynamicNavBarConfig = (): NavBarConfig => {
	// 基础导航栏链接
	const links: NavBarLink[] = [];

	// 主页
	links.push(LinkPresets.Home);

	// 文章及其子菜单
	links.push({
		name: "文章",
		url: "#",
		icon: "material-symbols:article",
		children: [
			// 归档
			LinkPresets.Archive,

			// 分类
			LinkPresets.Categories,

			// 标签
			LinkPresets.Tags,
		],
	});

	// 友链
	// 原本是一个叫“社交”的二级菜单（友链 + 留言）。留言板已整体移除，
	// 只剩一项的菜单没有存在意义，这里改成直接指向 /friends/ 的一级链接。
	links.push(LinkPresets.Friends);

	// 我的及其子菜单
	links.push({
		name: "我的",
		url: "#",
		icon: "material-symbols:person",
		children: [
			// 动态
			LinkPresets.Dynamic,

			// 相册
			LinkPresets.Gallery,

			// 追番
			LinkPresets.Anime,

			// VNDB
			LinkPresets.VNDB,

			// 番组计划
			LinkPresets.Bangumi,
		],
	});

	// 关于
	// 原本是个二级菜单（打赏 + 关于我）。打赏页已整体移除，只剩一项的菜单没有存在
	// 意义，这里改成直接指向 /about/ 的一级链接。
	links.push(LinkPresets.About);

	// 「链接」二级菜单（只有一条 GitHub，指向本站仓库）已整体移除。
	// 要加回来：links.push({ name: "链接", url: "#", icon: "material-symbols:link",
	//   children: [{ name: "GitHub", url: "...", external: true, icon: "fa7-brands:github" }] });

	// 文档链接
	// links.push({
	// 	name: "文档",
	// 	url: "https://docs-firefly.cuteleaf.cn",
	// 	external: true,
	// 	icon: "material-symbols:docs",
	// });

	return { links } as NavBarConfig;
};

